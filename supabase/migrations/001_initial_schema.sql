-- pgvector
create extension if not exists vector with schema extensions;


-- ============================================================
-- ENUMS
-- ============================================================

do $$
begin
    create type public.userrole as enum ('user', 'admin');
exception
    when duplicate_object then null;
end $$;


do $$
begin
    create type public.chatsource as enum ('playground', 'widget');
exception
    when duplicate_object then null;
end $$;


-- ============================================================
-- USERS
-- ============================================================

create table if not exists public.users (
    id integer generated by default as identity primary key,

    username varchar(64) not null unique,

    org_name varchar(120),

    password_hash varchar(255) not null,

    role public.userrole not null default 'user',

    is_active boolean not null default true,

    created_at timestamp without time zone default now(),

    last_login_at timestamp without time zone
);


-- ============================================================
-- USER SETTINGS
-- ============================================================

create table if not exists public.user_settings (
    id integer generated by default as identity primary key,

    user_id integer not null unique
        references public.users(id)
        on delete cascade,

    use_default_provider boolean not null default true,

    api_key varchar(255),

    base_url varchar(255),

    chat_model varchar(120),

    embedding_model varchar(120),

    system_prompt text,

    temperature double precision,

    top_k integer,

    similarity_threshold double precision,

    widget_id varchar(64) unique,

    widget_title varchar(120),

    widget_welcome_message text,

    widget_color varchar(16)
);


-- ============================================================
-- DOCUMENTS
-- ============================================================

create table if not exists public.documents (
    id integer generated by default as identity primary key,

    user_id integer not null
        references public.users(id)
        on delete cascade,

    title varchar(200) not null,

    content text not null,

    created_at timestamp without time zone default now(),

    updated_at timestamp without time zone default now()
);


-- ============================================================
-- CHUNKS
-- ============================================================

create table if not exists public.chunks (
    id integer generated by default as identity primary key,

    document_id integer not null
        references public.documents(id)
        on delete cascade,

    user_id integer not null
        references public.users(id)
        on delete cascade,

    chunk_index integer not null,

    text text not null,

    embedding extensions.vector(2560) not null,

    created_at timestamp without time zone default now()
);


-- ============================================================
-- CHAT SESSIONS
-- ============================================================

create table if not exists public.chat_sessions (
    id varchar(64) primary key,

    user_id integer not null
        references public.users(id)
        on delete cascade,

    source public.chatsource not null,

    visitor_label varchar(64),

    created_at timestamp without time zone default now()
);


-- ============================================================
-- CHAT MESSAGES
-- ============================================================

create table if not exists public.chat_messages (
    id integer generated by default as identity primary key,

    session_id varchar(64) not null
        references public.chat_sessions(id)
        on delete cascade,

    role varchar(16) not null,

    content text not null,

    is_flagged boolean default false,

    flag_reason varchar(255),

    resolved boolean default false,

    created_at timestamp without time zone default now()
);


-- ============================================================
-- INDEXES
-- ============================================================

create index if not exists idx_users_username_lower
on public.users (lower(username));


create index if not exists idx_documents_user_id
on public.documents(user_id);


create index if not exists idx_chunks_document_id
on public.chunks(document_id);


create index if not exists idx_chunks_user_id
on public.chunks(user_id);


create index if not exists idx_chat_sessions_user_id
on public.chat_sessions(user_id);


create index if not exists idx_chat_messages_session_id
on public.chat_messages(session_id);


-- ============================================================
-- ROW LEVEL SECURITY
-- ============================================================

alter table public.users enable row level security;

alter table public.user_settings enable row level security;

alter table public.documents enable row level security;

alter table public.chunks enable row level security;

alter table public.chat_sessions enable row level security;

alter table public.chat_messages enable row level security;